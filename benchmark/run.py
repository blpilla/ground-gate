"""Reproducible benchmark: GroundGate vs naive baselines.

Task: answer-level hallucination detection. Each case pairs one faithful and
one unfaithful answer over the same retrieved context; a system must block
the unfaithful answer (positive class) and let the faithful one through.

Systems compared:

- always_pass    — never blocks anything (what shipping without a gate does).
- answer_overlap — whole-answer token overlap with the context >= 0.7 passes.
                   This is the "aggregate similarity score" approach; it fails
                   because unfaithful answers overlap heavily with the context
                   everywhere except the hallucinated detail.
- groundgate     — claim-level deterministic gate, fail-closed, no LLM judge.

Run from the repository root (rewrites RESULTS.md):

    python benchmark/run.py
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from groundgate import verify
from groundgate.text import content_tokens

DATA = Path(__file__).parent / "data" / "cases.json"
RESULTS = Path(__file__).parent / "RESULTS.md"

OVERLAP_THRESHOLD = 0.7


def predict_always_pass(answer: str, context: list[dict]) -> bool:
    """Predict faithful for everything."""
    return True


def predict_answer_overlap(answer: str, context: list[dict]) -> bool:
    """Aggregate token overlap of the whole answer against all context."""
    answer_tokens = set(content_tokens(answer))
    context_tokens: set[str] = set()
    for source in context:
        context_tokens.update(content_tokens(source["text"]))
    if not answer_tokens:
        return True
    coverage = len(answer_tokens & context_tokens) / len(answer_tokens)
    return coverage >= OVERLAP_THRESHOLD


def predict_groundgate(answer: str, context: list[dict]) -> bool:
    return verify(answer, context).passed


SYSTEMS = {
    "always_pass": predict_always_pass,
    "answer_overlap": predict_answer_overlap,
    "groundgate": predict_groundgate,
}


def evaluate() -> tuple[dict, list[dict], int]:
    cases = json.loads(DATA.read_text("utf-8"))["cases"]
    rows: list[dict] = []
    # Positive class = unfaithful (the thing worth detecting).
    stats = {name: {"tp": 0, "fp": 0, "tn": 0, "fn": 0, "seconds": 0.0} for name in SYSTEMS}

    for case in cases:
        for label, answer in (("faithful", case["faithful"]), ("unfaithful", case["unfaithful"])):
            is_unfaithful = label == "unfaithful"
            row = {"case": case["name"], "domain": case["domain"], "label": label}
            for name, predict in SYSTEMS.items():
                start = time.perf_counter()
                predicted_pass = predict(answer, case["context"])
                stats[name]["seconds"] += time.perf_counter() - start
                predicted_unfaithful = not predicted_pass
                if is_unfaithful and predicted_unfaithful:
                    stats[name]["tp"] += 1
                elif is_unfaithful and not predicted_unfaithful:
                    stats[name]["fn"] += 1
                elif not is_unfaithful and predicted_unfaithful:
                    stats[name]["fp"] += 1
                else:
                    stats[name]["tn"] += 1
                row[name] = "block" if predicted_unfaithful else "pass"
            rows.append(row)
    return stats, rows, len(cases)


def metrics(counts: dict) -> dict:
    tp, fp, tn, fn = counts["tp"], counts["fp"], counts["tn"], counts["fn"]
    total = tp + fp + tn + fn
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "accuracy": (tp + tn) / total,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "ms_per_answer": counts["seconds"] / total * 1000,
    }


def render(stats: dict, rows: list[dict], n_cases: int) -> str:
    lines = [
        "# Benchmark results",
        "",
        "Generated by `python benchmark/run.py` — do not edit by hand.",
        "",
        f"**Task**: answer-level hallucination detection over {n_cases} paired",
        "faithful/unfaithful RAG answers from regulated domains (insurance,",
        f"health, legal; pt-BR). {n_cases * 2} answers total. Positive class =",
        "unfaithful answer (the gate must block it).",
        "",
        "GroundGate runs its deterministic core only: no LLM judge, fail-closed,",
        "zero network calls.",
        "",
        "| system | accuracy | precision | recall | F1 | ms/answer |",
        "|---|---|---|---|---|---|",
    ]
    for name in SYSTEMS:
        m = metrics(stats[name])
        lines.append(
            f"| {name} | {m['accuracy']:.2f} | {m['precision']:.2f} "
            f"| {m['recall']:.2f} | {m['f1']:.2f} | {m['ms_per_answer']:.2f} |"
        )
    lines += [
        "",
        "**Reading the table**: `always_pass` is what shipping without a gate",
        "does — it never catches anything. `answer_overlap` is the aggregate",
        "similarity approach used by naive filters; unfaithful answers slip",
        "through because they overlap heavily with the context everywhere",
        "except the hallucinated detail (a swapped number, an inverted",
        "coverage). GroundGate checks claim by claim, so the one wrong claim",
        "fails the whole answer.",
        "",
        "## Per-answer decisions",
        "",
        "| case | domain | label | " + " | ".join(SYSTEMS) + " |",
        "|---|---|---|" + "---|" * len(SYSTEMS),
    ]
    for row in rows:
        lines.append(
            f"| {row['case']} | {row['domain']} | {row['label']} | "
            + " | ".join(row[name] for name in SYSTEMS)
            + " |"
        )
    lines += [
        "",
        "## Honest caveats",
        "",
        "- This is a **seed benchmark**: curated pairs, answer-level labels,",
        "  small N. It demonstrates the failure mode aggregate scores have on",
        "  regulated-domain content; it is not an academic evaluation.",
        "- The unfaithful answers here hallucinate the way production RAG",
        "  actually fails (swapped numbers, inverted coverage statements,",
        "  citations pointing at the wrong source) — not adversarial",
        "  paraphrase attacks.",
        "- Contributions of harder cases are welcome, especially real",
        "  (anonymized) production failures.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    stats, rows, n_cases = evaluate()
    RESULTS.write_text(render(stats, rows, n_cases), "utf-8")
    for name in SYSTEMS:
        m = metrics(stats[name])
        print(
            f"{name:>16}: acc={m['accuracy']:.2f} P={m['precision']:.2f} "
            f"R={m['recall']:.2f} F1={m['f1']:.2f} {m['ms_per_answer']:.2f}ms/answer"
        )
    print(f"\nwrote {RESULTS}")
